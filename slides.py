"""Turn an Analysis into a clean PowerPoint deck."""
from __future__ import annotations

import tempfile
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.util import Inches, Pt

from urva.analyst import Analysis

NAVY, GOLD, WHITE = RGBColor(0x14, 0x21, 0x3D), RGBColor(0xE0, 0xA4, 0x2B), RGBColor(0xFF, 0xFF, 0xFF)


def _bg(slide):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = NAVY


def _text(slide, txt, x, y, w, h, size=18, bold=False, color=WHITE):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h)).text_frame
    tb.word_wrap = True
    lines = txt if isinstance(txt, list) else [txt]
    for i, line in enumerate(lines):
        p = tb.paragraphs[0] if i == 0 else tb.add_paragraph()
        p.text = line
        p.font.size, p.font.bold, p.font.color.rgb = Pt(size), bold, color
        p.space_after = Pt(8)


def _chart(a: Analysis, tmp: Path) -> Path | None:
    if not (a.categorical and a.numeric) or a.df is None:
        return None
    g = a.df.groupby(a.categorical[0])[a.numeric[0]].sum().sort_values().tail(10)
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    ax.barh(g.index.astype(str), g.values, color="#E0A42B")
    ax.set_title(f"{a.numeric[0]} by {a.categorical[0]}", color="white")
    fig.patch.set_facecolor("#14213D"); ax.set_facecolor("#14213D")
    ax.tick_params(colors="white")
    for s in ax.spines.values():
        s.set_visible(False)
    fig.tight_layout()
    out = tmp / "chart.png"
    fig.savefig(out, facecolor=fig.get_facecolor())
    plt.close(fig)
    return out


def build_deck(a: Analysis, out: str | Path) -> Path:
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    blank = prs.slide_layouts[6]

    s = prs.slides.add_slide(blank); _bg(s)
    _text(s, a.name, 0.8, 2.6, 11.5, 1.2, 40, True)
    _text(s, f"{a.rows:,} rows · {a.cols} columns · auto-generated by Urva", 0.8, 3.8, 11.5, 0.6, 18, color=GOLD)

    s = prs.slides.add_slide(blank); _bg(s)
    _text(s, "Key insights", 0.8, 0.5, 11.5, 0.8, 30, True, GOLD)
    _text(s, [f"• {i}" for i in a.insights] or ["• No notable patterns found."], 0.8, 1.5, 11.7, 5.5, 20)

    with tempfile.TemporaryDirectory() as d:
        img = _chart(a, Path(d))
        if img:
            s = prs.slides.add_slide(blank); _bg(s)
            _text(s, "Breakdown", 0.8, 0.4, 11.5, 0.8, 30, True, GOLD)
            s.shapes.add_picture(str(img), Inches(1.4), Inches(1.4), width=Inches(10.5))

    if not a.stats.empty:
        s = prs.slides.add_slide(blank); _bg(s)
        _text(s, "Summary statistics", 0.8, 0.4, 11.5, 0.8, 30, True, GOLD)
        st = a.stats[["mean", "min", "max"]].head(8)
        tbl = s.shapes.add_table(len(st) + 1, 4, Inches(0.8), Inches(1.5), Inches(11.7), Inches(0.5)).table
        for j, h in enumerate(["Metric", "Mean", "Min", "Max"]):
            tbl.cell(0, j).text = h
        for i, (idx, row) in enumerate(st.iterrows(), 1):
            for j, v in enumerate([idx, *row.values]):
                tbl.cell(i, j).text = v if isinstance(v, str) else f"{v:,.2f}"

    out = Path(out)
    prs.save(out)
    return out
